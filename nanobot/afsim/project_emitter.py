"""Emit a ScenarioIR as a multi-file AFSIM project.

真实 AFSIM 想定从来不是一个单文件。官方 demo 语料 (4749 个 txt, 1121 个目录) 里
每个想定都是一个目录: 主入口 + 类型定义 + 平台/传感器/武器子目录 + 事件输出。
之前 `AfsimCompiler.compile()` 用单个 jinja 模板把所有东西塞进一个 txt —— 语法
合法但**不符合真实工程组织**, 也不方便复用类型定义 (4 架轰-6K 写 4 遍 platform_type
定义就是浪费)。

这个模块按官方 demo 的标准组织输出:

    <project_root>/
    ├── main.txt                  # 入口: file_path . + include + 实例 + 时间轴
    ├── _common.txt               # 聚合 include: 类型定义 + 共享签名
    ├── sensors/<type_id>.txt     # 每种 sensor 类型一个文件
    ├── weapons/<type_id>.txt     # 每种 weapon_effects 一个文件
    ├── platforms/<type_id>.txt   # 每种 platform_type 一个文件
    ├── event_output.txt          # 事件输出配置
    └── output/                   # 运行时产物目录 (mission.log 等)

设计要点:

- **类型 vs 实例分离**: `sensors/KJ500_RADAR.txt` 定义类型, `main.txt` 里
  `add sensor radar KJ500_RADAR` 创建实例。4 架轰-6K 共享同一个 `H6K` 类型定义,
  各自在 main.txt 里有独立的 `platform blue_h6k_1 H6K` / `blue_h6k_2 H6K` ...
- **include_once 而非 include**: 防止重复加载。官方 demo 里 `include_once` 是主流。
- **file_path .**: 让相对路径从项目根解析, 与官方 demo 一致。
- **每种类型只写一次**: 多个平台共享同一 sensor_type_id 时, 类型文件只生成一份。
- **platform_type 命名**: 用 IR 里的 `platform_type` 字段 (如 `H6K`, `KJ500`, `DDG`)
  作为类型文件名, 与 AFSIM 的 `platform_type NAME [PARENT]` 语法对齐。
- **共享雷达签名**: 官方 demo 把 `radar_signature` 放在 `_common.txt` 里, 所有平台
  共用。这里也这么做: 一个 `10dB_FuzzBall` 签名, 所有平台 `radar_signature 10dB_FuzzBall`。
- **事件输出/事件管道/结束时间**: 单独一个 `event_output.txt`, 由 main.txt include。
  这样 main.txt 只关心"有什么 + 在什么位置 + 做什么", 输出配置独立可换。
- **output/ 目录**: 创建空目录占位, 真实 AFSIM 会把 `mission.log` / `replay.aer`
  写到这里。我们只放一个 `.gitkeep`。

向后兼容:
    旧的 `AfsimCompiler.compile()` 仍然可用, 仍然产出单文件。
    新的 `emit_project()` 返回 `{relative_path: content}` 字典, 由调用方决定写盘。
    `write_project()` 是便利封装, 直接写到指定目录。

与单文件编译的等价性:
    把 project 里所有 txt 按 include 顺序拼接, 应该和 `compile()` 输出语义等价
    (允许空白/注释差异)。这是回归测试的判据。
"""

from __future__ import annotations

from pathlib import Path

from .compiler import _number, _position, _route_position
from .schemas import (
    PlatformIR,
    ScenarioIR,
    SensorIR,
)


def _header(purpose: str) -> str:
    return (
        "# ****************************************************************************\n"
        f"# AFSIM scenario - {purpose}\n"
        "# Generated by afsim-scenario-builder. Validate before execution.\n"
        "# ****************************************************************************\n"
    )


def _render_sensor_type(sensor: SensorIR) -> str:
    """一种 sensor 类型的完整定义, 写到 sensors/<type_id>.txt。"""
    lines = [
        _header(f"sensor type {sensor.sensor_type_id}"),
        f"sensor {sensor.sensor_type_id} {sensor.base_type}",
        "   mode_template",
        f"      frame_time {_number(sensor.frame_time_s)} sec",
    ]
    if sensor.reports_location:
        lines.append("      reports_location")
    lines += [
        "   end_mode_template",
        f"   mode {sensor.mode_name}",
        f"      maximum_range {_number(sensor.maximum_range_m)} m",
        "   end_mode",
    ]
    if sensor.ignore_same_side:
        lines.append("   ignore_same_side")
    lines.append("end_sensor")
    lines.append("")
    return "\n".join(lines)


def _render_weapon_effects_type(weapon_type: str) -> str:
    """weapon_effects 类型定义, 写到 weapons/<weapon_type>.txt。

    所有用 WSF_IMPLICIT_WEAPON / WSF_EXPLICIT_WEAPON 的平台共享同一个 effects 定义。
    命名沿用单文件模板的 ``AUTO_ENGAGEMENT_EFFECT`` —— 这是共享效应名, 不是武器
    类型名。武器类型名 (WSF_IMPLICIT_WEAPON) 出现在 ``add weapon NAME TYPE`` 里,
    而 weapon_effects 块用的是 ``AUTO_ENGAGEMENT_EFFECT``。两者不同概念。
    """
    return (
        _header(f"weapon effects (used by {weapon_type})")
        + "weapon_effects AUTO_ENGAGEMENT_EFFECT WSF_SPHERICAL_LETHALITY\n"
        + "   maximum_damage 1\n"
        + "   minimum_damage 0.99\n"
        + "   maximum_radius 100 km\n"
        + "   minimum_radius 0 m\n"
        + "end_weapon_effects\n"
    )


def _mover_suffix(mover_type: str) -> str:
    """把 mover 类型名转成短后缀, 用于生成类型文件名。

    同一基型 (如 WSF_PLATFORM) 按 mover 分家时, 后缀让文件名能区分:
    WSF_PLATFORM + WSF_AIR_MOVER     -> WSF_PLATFORM_AIR
    WSF_PLATFORM + WSF_SURFACE_MOVER -> WSF_PLATFORM_SURFACE
    WSF_PLATFORM (无 mover)          -> WSF_PLATFORM
    """
    return mover_type.removeprefix("WSF_").removesuffix("_MOVER")


def _render_platform_type(
    type_key: str,
    base_type: str,
    mover_type: str | None,
) -> str:
    """一种 platform_type 的定义, 写到 platforms/<type_key>.txt。

    只写类型层面的属性 (mover、雷达签名), 不写实例层面的 (位置、航路、传感器挂载)。

    ``type_key`` 是文件/类型名 (如 ``H6K_AIR``), ``base_type`` 是 AFSIM 里的
    ``platform_type`` 声明名 (如 ``H6K``)。两者可以不同: 同一个 ``H6K`` 基型,
    按 mover 分家成 ``H6K_AIR`` / ``H6K_SURFACE`` 等多个文件, 避免"所有平台共享
    首个平台的 mover"这种错误。
    """
    lines = [
        _header(f"platform type {type_key} (base {base_type})"),
        f"platform_type {type_key}",
    ]
    if mover_type:
        # mover 在 platform_type 里是单行引用 (与官方 demo 一致), 不是带 end_mover 的块。
        # 验证器的 end_* 配额法处理不了嵌套: 内层 end_mover 会被误判成闭合外层
        # platform_type, 触发 block.mismatch。
        lines.append(f"   mover {mover_type}")
    # 共享雷达签名: 官方 demo 把 signature 放在类型定义里, 所有实例继承。
    # 这里简化为"所有平台共用一个 10dB_FuzzBall"。
    lines += [
        "   radar_signature 10dB_FuzzBall",
        "      constant 10 dBsm",
        "   end_radar_signature",
    ]
    lines.append("")
    return "\n".join(lines)


def _render_platform_instance(
    platform: PlatformIR,
    scenario: ScenarioIR,
) -> str:
    """一个平台实例, 写到 main.txt 里。

    实例只负责: 我是谁 (side/position)、挂什么 (sensor/weapon)、走哪 (route)、
    什么时候开火 (execute)。类型层面的东西 (mover、signature) 在 platform_type 里。

    实例引用的类型名必须与 ``emit_project()`` 里生成的 ``type_key`` 一致
    (按 mover 分家: ``H6K_AIR`` / ``H6K_SURFACE`` / ``H6K``)。
    """
    type_key = (
        platform.platform_type
        if platform.mover_type is None
        else f"{platform.platform_type}_{_mover_suffix(platform.mover_type)}"
    )
    lines = [
        f"platform {platform.platform_id} {type_key}",
        f"   side {platform.side.value}",
        f"   position {_position(platform.position)} "
        f"heading {_number(platform.heading_deg)} deg",
    ]
    for sensor in platform.sensors:
        on_off = "on" if sensor.enabled else "off"
        lines += [
            f"   add sensor {sensor.instance_name} {sensor.sensor_type_id}",
            f"      {on_off}",
            f"      initial_mode {sensor.initial_mode}",
            "   end_sensor",
        ]
    for weapon in platform.weapons:
        lines += [
            f"   add weapon {weapon.instance_name} {weapon.weapon_type}",
            f"      update_interval {_number(weapon.update_interval_s)} sec",
            "      weapon_effects AUTO_ENGAGEMENT_EFFECT",
            f"      quantity {weapon.quantity}",
            "   end_weapon",
        ]
    if platform.route:
        lines.append("   route")
        for point in platform.route:
            lines.append(f"      position {_route_position(point)}")
        lines.append("   end_route")
    # 交战脚本: 这个平台作为 shooter 的所有 engagement
    for engagement in scenario.engagements:
        if engagement.shooter_platform == platform.platform_id:
            lines += [
                f"   execute at_time {_number(engagement.fire_time_s)} sec absolute",
                f'      Weapon("{engagement.weapon_name}").Fire('
                f'WsfSimulation.FindPlatform("{engagement.target_platform}").MakeTrack());',
                "   end_execute",
            ]
    lines += ["end_platform", ""]
    return "\n".join(lines)


def _render_common(includes: list[str]) -> str:
    """_common.txt: 聚合所有类型文件的 include_once。"""
    lines = [_header("common type definitions")]
    for inc in includes:
        lines.append(f"include_once {inc}")
    lines.append("")
    return "\n".join(lines)


def _render_event_output() -> str:
    return (
        _header("event output configuration")
        + "event_output\n"
        + "   file events.evt\n"
        + "   enable SENSOR_DETECTION_ATTEMPT\n"
        + "   enable SENSOR_TRACK_INITIATED\n"
        + "   enable WEAPON_FIRED\n"
        + "end_event_output\n"
        + "\n"
        + "event_pipe\n"
        + "   file replay.aer\n"
        + "end_event_pipe\n"
    )


def _render_main(scenario: ScenarioIR, common_includes: list[str]) -> str:
    """main.txt: 入口文件。

    结构:
        file_path .
        log_file output/mission.log
        include_once _common.txt
        end_time ... sec

        # 平台实例
        platform blue_h6k_1 H6K
           ...
        end_platform
        ...
    """
    lines = [
        _header(f"scenario {scenario.scenario_id}"),
        "file_path .",
        "",
        "log_file output/mission.log",
        "",
        "include_once _common.txt",
        "",
        f"// scenario_id: {scenario.scenario_id}",
        f"// mission_id: {scenario.mission.mission_id}",
        f"// mission_name: {scenario.mission.name}",
        "",
    ]
    for platform in scenario.platforms:
        lines.append(_render_platform_instance(platform, scenario))
    lines.append("include_once event_output.txt")
    lines.append("")
    lines.append(f"end_time {_number(scenario.mission.duration_s)} sec")
    lines.append("")
    return "\n".join(lines)


def emit_project(scenario: ScenarioIR) -> dict[str, str]:
    """把 ScenarioIR 编译成多文件项目, 返回 {相对路径: 文件内容}。

    返回的字典可以直接交给 `write_project()` 写盘, 也可以在内存里校验
    (比如测试 include 链是否闭合、类型是否都定义了)。
    """
    files: dict[str, str] = {}

    # 1. 收集所有类型定义, 每种只写一次
    sensor_types: dict[str, SensorIR] = {}
    for sensor in scenario.sensors:
        sensor_types.setdefault(sensor.sensor_type_id, sensor)
    for type_id, sensor in sensor_types.items():
        files[f"sensors/{type_id}.txt"] = _render_sensor_type(sensor)

    weapon_types: set[str] = set()
    for platform in scenario.platforms:
        for weapon in platform.weapons:
            weapon_types.add(weapon.weapon_type)
    for weapon_type in sorted(weapon_types):
        files[f"weapons/{weapon_type}.txt"] = _render_weapon_effects_type(weapon_type)

    platform_types: dict[str, tuple[str, str | None]] = {}
    for platform in scenario.platforms:
        # 按 (platform_type, mover_type) 分家: 同一基型不同 mover 得拆成多个文件,
        # 否则所有平台会共享首个平台的 mover (4 架轰-6K 的 WSF_AIR_MOVER 会污染
        # 红方巡洋舰和岸基雷达)。
        mover = platform.mover_type
        type_key = (
            platform.platform_type
            if mover is None
            else f"{platform.platform_type}_{_mover_suffix(mover)}"
        )
        platform_types.setdefault(type_key, (platform.platform_type, mover))
    for type_key, (base_type, mover_type) in platform_types.items():
        files[f"platforms/{type_key}.txt"] = _render_platform_type(
            type_key, base_type, mover_type
        )

    # 2. event_output.txt
    files["event_output.txt"] = _render_event_output()

    # 3. _common.txt: 聚合所有类型 include
    common_includes = [f"sensors/{t}.txt" for t in sorted(sensor_types)]
    common_includes += [f"weapons/{t}.txt" for t in sorted(weapon_types)]
    common_includes += [f"platforms/{t}.txt" for t in sorted(platform_types)]
    files["_common.txt"] = _render_common(common_includes)

    # 4. main.txt: 入口
    files["main.txt"] = _render_main(scenario, common_includes)

    # 5. output/ 占位
    files["output/.gitkeep"] = ""

    return files


def write_project(scenario: ScenarioIR, root: Path) -> dict[str, Path]:
    """把 emit_project() 的结果写到磁盘, 返回 {相对路径: 绝对路径}。

    `root` 不存在会创建; 已存在会**覆盖**同名文件 (这是预期: 重新生成想定就该覆盖)。
    """
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for rel_path, content in emit_project(scenario).items():
        full = root / rel_path
        full.parent.mkdir(parents=True, exist_ok=True)
        full.write_text(content, encoding="utf-8")
        written[rel_path] = full
    return written
